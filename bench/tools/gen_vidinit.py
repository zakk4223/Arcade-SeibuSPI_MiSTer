#!/usr/bin/env python3
"""Turn a captured rfjet video-init trace into a NASM replay table.

The benchmark ROM has to bring the video hardware up on a real PCB, and neither
emulator can tell it how: MAME hardcodes rfjet's tile decryption keys and its
tile_decrypt_key_w only logs (seibuspi_v.cpp:140), while the core hardcodes
TKEY*_RFJET in spi_defs.vh.  The game writes six 16-bit words to 0x414 that both
emulators throw away.  So rather than reverse engineer the RISE chip, replay what
the game itself does, verbatim and in order.

Input is the trace bench/tools/mame_vidinit_trace.lua produces (see
bench/vidinit_trace.txt).  Output is a table of 8-byte entries:

    dd  addr | 0x80000000 if the store is 32-bit
    dd  value, right-justified

A mask of FFFF0000 is a 16-bit store to addr+2, and is emitted that way, so the
replay loop only has to know two widths.

    python3 bench/tools/gen_vidinit.py bench/vidinit_trace.txt > bench/vidinit.inc
"""
import re
import sys

LINE = re.compile(r"^\s*[\d.]+\s+W\s+([0-9A-Fa-f]{3})\s+([0-9A-Fa-f]{8})\s+mask=([0-9A-Fa-f]{8})\s*$")


def main():
    src = sys.argv[1]
    out = []
    for line in open(src):
        m = LINE.match(line)
        if not m:
            continue
        addr, data, mask = (int(g, 16) for g in m.groups())
        if mask == 0xFFFFFFFF:
            out.append((addr, data, True))
        elif mask == 0x0000FFFF:
            out.append((addr, data & 0xFFFF, False))
        elif mask == 0xFFFF0000:
            out.append((addr + 2, data >> 16, False))
        else:
            sys.exit("%s: unhandled mask %08X at %03X" % (src, mask, addr))

    print("; Generated by bench/tools/gen_vidinit.py from %s -- do not edit." % src)
    print("; %d register writes, replayed verbatim in the game's own order." % len(out))
    print("")
    print("VIDINIT_COUNT equ %d" % len(out))
    print("")
    print("vidinit_table:")
    for addr, val, is32 in out:
        tag = "dd" if is32 else "dw"
        print("    dd 0x%08X" % (addr | (0x80000000 if is32 else 0)))
        print("    dd 0x%08X            ; %s [0x%03X]" % (val, tag, addr))
    print("vidinit_table_end:")


if __name__ == "__main__":
    main()
